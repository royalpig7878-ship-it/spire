// catalog.js
//
// The facility catalog: every building type you can build, with its price,
// size, income and effects. It is part of the game's configuration (config.js
// imports it as `config.facilities`), kept in its own file because it is long.
//
// Common fields
//   name, category (which toolbar tab), width (cells), cost (build price;
//   per FLOOR for `vertical` types), minFloor / maxFloor (allowed floors;
//   negative = basement), color + accent (the vector art palette).
//   rentPerCell: rent per occupied cell per QUARTER.
//   upkeepPerCell: running cost per cell per DAY.
//   style / icon: how it is drawn (see src/render/facilities.js).
//   tags: what the building "is", used by district synergy bonuses.
// People
//   tenantKind: worker | resident | guest, and capacity = how many live/work here.
// Venues (people visit them for money and stress relief)
//   purposes: what a visit is for (food | shop | fun | care | fit)
//   visitRevenue: money per visit, visitCapacity: visitors at once,
//   visitRelief: stress removed per visit.
// Effects
//   noise: how loud it is for neighbours (see `services` in config.js)
//   serviceKind (security | medical | maintenance) + coverFloors: floors it covers
//   cleanPerDay (maintenance), trashCut + dailyIncome (recycling),
//   powerSupply (substation), parkingCapacity (garage),
//   amenityReach + amenityRelief (atrium), climbSecPerFloor (escalator).

